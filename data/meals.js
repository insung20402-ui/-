function getMealsForMonth(year, month) {
  // month: 1-12
  const prefix = `${year}-${String(month).padStart(2, "0")}`;
  return Object.keys(MEALS)
    .filter((d) => d.startsWith(prefix))
    .sort()
    .map((d) => ({ date: d, menu: MEALS[d] }));
}
