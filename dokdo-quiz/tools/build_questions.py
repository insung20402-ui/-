JOSA = {"이라는": ("이라는", "라는"), "으로": ("으로", "로"), "가": ("이", "가"), "를": ("을", "를"), "이라": ("이라", "라")}


def fill(stmt, word):
    """'{}' 자리에 word 를 넣고, 받침에 맞춰 조사({으로} 등)를 고른다."""
    last = next((ch for ch in reversed(word) if "가" <= ch <= "힣"), None)
    jong = (ord(last) - 0xAC00) % 28 if last else 0
    out = stmt.replace("{}", word, 1)
    for key, (with_b, without_b) in JOSA.items():
        if key == "으로":
            pick = with_b if jong not in (0, 8) else without_b  # ㄹ 받침(8)은 '로'
        else:
            pick = with_b if jong else without_b
        out = out.replace("{" + key + "}", pick)
    return out


def build():
    rnd = random.Random(20261025)  # 고정 시드 → 다시 실행해도 같은 결과
    out = []

    def add(qid, fact, cat, level, typ, q, choices=None, answer=None, exp=""):
        item = {"id": qid, "f": fact, "c": cat, "l": level, "t": typ, "q": q, "e": exp}
        if typ == "mc":
            item["o"] = choices
        item["a"] = answer
        out.append(item)

    for i, f in enumerate(FACTS, 1):
        fid = f"F{i:03d}"
        add(f"{fid}m", fid, f["cat"], f["level"], "mc", f["q"], [f["ans"]] + f["wrong"], 0, f["exp"])
        if f["stmt"]:
            add(f"{fid}o", fid, f["cat"], max(1, f["level"] - 1), "ox", fill(f["stmt"], f["ans"]), answer=True, exp="O! " + f["exp"])
            wrong = rnd.choice(f["wrong"])
            add(f"{fid}x", fid, f["cat"], f["level"], "ox", fill(f["stmt"], wrong), answer=False,
                exp=f"X! '{wrong}'이(가) 아니라 '{f['ans']}'입니다. " + f["exp"])
        if f["rev"]:
            rq, rwrong = f["rev"]
            add(f"{fid}r", fid, f["cat"], f["level"], "mc", rq, [REV_ANSWERS[fid]] + rwrong, 0, f["exp"])

    for i, o in enumerate(OX_ONLY, 1):
        oid = f"X{i:03d}"
        add(oid, oid, o["cat"], o["level"], "ox", o["stmt"], answer=o["truth"], exp=("O! " if o["truth"] else "X! ") + o["exp"])

    # 연도 맞히기
    years = [y for y, _ in TIMELINE]
    for i, (y, ev) in enumerate(TIMELINE, 1):
        tid = f"T{i:02d}"
        near = sorted((yy for yy in years if yy != y), key=lambda yy: abs(yy - y))[:6]
        wrong = rnd.sample(near, 3)
        add(f"{tid}y", tid, "연표", 3 if y < 1900 else 2, "mc", f"'{ev}'은(는) 몇 년의 일일까?",
            [f"{y}년"] + [f"{w}년" for w in wrong], 0, f"{y}년의 일입니다.")

    # 순서 문제: 가장 먼저 / 가장 나중 (4지선다), 두 사건 비교 (O/X)
    seen = set()
    n = 0
    while n < 76:
        picks = tuple(sorted(rnd.sample(range(len(TIMELINE)), 4)))
        mode = rnd.choice(["first", "last"])
        if (picks, mode) in seen:
            continue
        seen.add((picks, mode))
        n += 1
        evs = [TIMELINE[p] for p in picks]
        right = evs[0] if mode == "first" else evs[-1]
        others = [e for e in evs if e != right]
        word = "가장 먼저" if mode == "first" else "가장 나중에"
        span = evs[-1][0] - evs[0][0]
        lvl = 3 if span < 150 else 2
        exp = " → ".join(f"{y}년 {e}" for y, e in evs)
        add(f"S{n:03d}", f"S{n:03d}", "연표", lvl, "mc", f"다음 중 {word} 일어난 일은?",
            [right[1]] + [e[1] for e in others], 0, "순서: " + exp)
    n = 0
    pairs = set()
    while n < 60:
        a, b = rnd.sample(range(len(TIMELINE)), 2)
        if (a, b) in pairs or (b, a) in pairs:
            continue
        pairs.add((a, b))
        n += 1
        (ya, ea), (yb, eb) = TIMELINE[a], TIMELINE[b]
        lvl = 3 if abs(ya - yb) < 30 else (2 if abs(ya - yb) < 200 else 1)
        add(f"P{n:03d}", f"P{n:03d}", "연표", lvl, "ox", f"'{ea}'은(는) '{eb}'보다 먼저 일어난 일이다.",
            answer=ya < yb, exp=("O! " if ya < yb else "X! ") + f"{ea}({ya}년), {eb}({yb}년)")
    return out


